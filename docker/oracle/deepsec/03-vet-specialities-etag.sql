-- Persist a hash of each vet's sorted speciality IDs so link changes affect SYS_ROW_ETAG.
-- Safe to run on both fresh and previously initialized DeepSec schemas.

WHENEVER SQLERROR EXIT SQL.SQLCODE
SET DEFINE OFF
SET VERIFY OFF

DECLARE
  column_count PLS_INTEGER;
BEGIN
  SELECT COUNT(*)
    INTO column_count
    FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'VETS'
     AND COLUMN_NAME = 'SPECIALITIES_ETAG_HASH';

  IF column_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE VETS ADD (SPECIALITIES_ETAG_HASH VARCHAR2(64) DEFAULT ''E3B0C44298FC1C149AFBF4C8996FB92427AE41E4649B934CA495991B7852B855'' NOT NULL)';
  END IF;
END;
/

UPDATE VETS v
   SET SPECIALITIES_ETAG_HASH = UPPER(RAWTOHEX(STANDARD_HASH(
       NVL((
         SELECT LISTAGG(TO_CHAR(vs.SPECIALTY_ID, 'FM9999999990', 'NLS_NUMERIC_CHARACTERS=''.,'''), ',')
                  WITHIN GROUP (ORDER BY vs.SPECIALTY_ID)
           FROM VET_SPECIALTIES vs
          WHERE vs.VET_ID = v.ID
       ), ''),
       'SHA256'
   )));
COMMIT;
